-- Etapa 2, módulo 1: categorías, artículos y costo por ámbito. Ver docs/modelo-datos.dbml.

create table categorias (
    id          bigint generated by default as identity primary key,
    nombre      varchar(120) not null,
    descripcion text,
    activo      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now()
);

create unique index uq_categorias_nombre on categorias (lower(nombre));

create table articulos (
    id            bigint generated by default as identity primary key,
    ambito_id     bigint       not null references ambitos (id),
    tipo          varchar(20)  not null check (tipo in ('insumo', 'producto_terminado', 'reventa')),
    nombre        varchar(200) not null,
    descripcion   text,
    categoria_id  bigint       references categorias (id),
    marca         varchar(120),
    unidad_medida varchar(10)  not null check (unidad_medida in ('unidad', 'kg', 'litro', 'm3', 'dm3')),
    imagen        varchar(255) check (imagen like 'assets/productos/_%' and imagen not like '%..%'),
    alicuota_iva  numeric(4,2) not null check (alicuota_iva in (0, 10.5, 21, 27)),
    visible_web   boolean      not null default false,
    activo        boolean      not null default true,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    -- los insumos no tienen categoría; los productos terminados y la reventa, sí
    check ((tipo = 'insumo') = (categoria_id is null)),
    check (tipo <> 'insumo' or not visible_web)
);

create unique index uq_articulos_nombre on articulos (ambito_id, lower(nombre));
create index ix_articulos_categoria on articulos (categoria_id);

-- La reventa es de un local; los insumos y los productos terminados, de la fábrica.
create function articulos_ambito_segun_tipo() returns trigger
language plpgsql as $$
declare
    tipo_ambito varchar;
begin
    select tipo into tipo_ambito from ambitos where id = new.ambito_id;
    if (new.tipo = 'reventa') <> (tipo_ambito = 'local') then
        raise exception 'Un artículo de tipo % no puede ser de un ámbito de tipo %.', new.tipo, tipo_ambito
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger articulos_ambito_segun_tipo
    before insert or update of tipo, ambito_id on articulos
    for each row execute function articulos_ambito_segun_tipo();

create table costos_articulo (
    id           bigint generated by default as identity primary key,
    articulo_id  bigint         not null references articulos (id),
    ambito_id    bigint         not null references ambitos (id),
    costo_actual numeric(14,2)  not null check (costo_actual >= 0),
    created_at   timestamptz    not null default now(),
    updated_at   timestamptz    not null default now(),
    unique (articulo_id, ambito_id)
);

-- Un ámbito tiene costo de sus propios artículos, y un local además de los productos terminados de la fábrica.
create function costos_articulo_ambito_valido() returns trigger
language plpgsql as $$
declare
    duenio_articulo bigint;
    tipo_articulo   varchar;
    tipo_ambito     varchar;
begin
    select ambito_id, tipo into duenio_articulo, tipo_articulo from articulos where id = new.articulo_id;
    select tipo into tipo_ambito from ambitos where id = new.ambito_id;
    if new.ambito_id <> duenio_articulo
            and not (tipo_articulo = 'producto_terminado' and tipo_ambito = 'local') then
        raise exception 'El ámbito % no puede tener costo del artículo %.', new.ambito_id, new.articulo_id
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger costos_articulo_ambito_valido
    before insert or update of articulo_id, ambito_id on costos_articulo
    for each row execute function costos_articulo_ambito_valido();
