-- Etapa 2, módulo 3: ubicaciones, stock por ubicación y movimientos de stock. Ver docs/modelo-datos.dbml.
-- El stock es la suma de los movimientos. stock_articulos.cantidad_actual es un caché que mantiene la base con un
-- trigger, así no se puede desincronizar aunque se inserten movimientos por fuera de la aplicación.
-- movimientos_stock se crea sin venta_id, pedido_id, compra_id, entrega_id ni conteo_id: cada una se agrega con
-- su módulo. lote_id va sin FK hasta que exista lotes_produccion (etapa 4).

create table ubicaciones_stock (
    id         bigint generated by default as identity primary key,
    ambito_id  bigint       not null references ambitos (id),
    nombre     varchar(120) not null,
    activo     boolean      not null default true,
    created_at timestamptz  not null default now(),
    updated_at timestamptz  not null default now()
);

create unique index uq_ubicaciones_stock_nombre on ubicaciones_stock (ambito_id, lower(nombre));

-- Cada ámbito nace con una ubicación "Principal"; los que ya existen la reciben acá.
create function ambitos_ubicacion_principal() returns trigger
language plpgsql as $$
begin
    insert into ubicaciones_stock (ambito_id, nombre) values (new.id, 'Principal');
    return new;
end;
$$;

create trigger ambitos_ubicacion_principal
    after insert on ambitos
    for each row execute function ambitos_ubicacion_principal();

insert into ubicaciones_stock (ambito_id, nombre) select id, 'Principal' from ambitos;

create table stock_articulos (
    id                 bigint generated by default as identity primary key,
    articulo_id        bigint        not null references articulos (id),
    ubicacion_stock_id bigint        not null references ubicaciones_stock (id),
    stock_minimo       numeric(14,3) check (stock_minimo >= 0),
    stock_maximo       numeric(14,3) check (stock_maximo >= 0),
    cantidad_actual    numeric(14,3) not null default 0,
    created_at         timestamptz   not null default now(),
    updated_at         timestamptz   not null default now(),
    unique (articulo_id, ubicacion_stock_id),
    check (stock_maximo is null or stock_minimo is null or stock_maximo >= stock_minimo),
    -- el stock no puede quedar negativo: el movimiento que lo dejaría así falla y revierte su transacción
    constraint stock_articulos_sin_negativo check (cantidad_actual >= 0)
);

create index ix_stock_articulos_ubicacion on stock_articulos (ubicacion_stock_id);

create table movimientos_stock (
    id                 bigint generated by default as identity primary key,
    articulo_id        bigint        not null references articulos (id),
    ubicacion_stock_id bigint        not null references ubicaciones_stock (id),
    tipo               varchar(30)   not null check (tipo in ('venta', 'entrega_pedido', 'compra', 'entrega_salida',
                                         'entrega_recepcion', 'produccion_consumo', 'produccion_ingreso', 'ajuste',
                                         'conteo', 'anulacion', 'devolucion')),
    cantidad           numeric(14,3) not null check (cantidad <> 0),
    lote_id            bigint,
    usuario_id         bigint        not null references usuarios (id),
    fecha_hora         timestamptz   not null default now(),
    motivo             varchar(255),
    observaciones      text,
    created_at         timestamptz   not null default now(),
    updated_at         timestamptz   not null default now(),
    -- todo ajuste manual exige un motivo
    check (tipo <> 'ajuste' or coalesce(length(trim(motivo)), 0) > 0)
);

create index ix_movimientos_stock_articulo on movimientos_stock (articulo_id, ubicacion_stock_id, fecha_hora desc);
create index ix_movimientos_stock_ubicacion on movimientos_stock (ubicacion_stock_id, fecha_hora desc);

-- Un ámbito tiene stock de los artículos que ve: los suyos y, si es un local, los productos terminados de la
-- fábrica. Es la restricción de que la ubicación pertenezca al ámbito del artículo (plan de la etapa 2).
create function stock_articulo_valido_en_ubicacion(articulo bigint, ubicacion bigint) returns void
language plpgsql as $$
declare
    ambito_articulo  bigint;
    tipo_articulo    varchar;
    ambito_ubicacion bigint;
    tipo_ambito      varchar;
begin
    select ambito_id, tipo into ambito_articulo, tipo_articulo from articulos where id = articulo;
    select u.ambito_id, a.tipo into ambito_ubicacion, tipo_ambito
    from ubicaciones_stock u join ambitos a on a.id = u.ambito_id where u.id = ubicacion;
    if ambito_articulo <> ambito_ubicacion
            and not (tipo_articulo = 'producto_terminado' and tipo_ambito = 'local') then
        raise exception 'La ubicación % no puede tener stock del artículo %.', ubicacion, articulo
            using errcode = 'check_violation';
    end if;
end;
$$;

-- Antes de insertar un movimiento: el artículo debe poder estar en la ubicación y, si se mide en unidades, la
-- cantidad debe ser entera.
create function movimientos_stock_validar() returns trigger
language plpgsql as $$
declare
    unidad varchar;
begin
    perform stock_articulo_valido_en_ubicacion(new.articulo_id, new.ubicacion_stock_id);
    select unidad_medida into unidad from articulos where id = new.articulo_id;
    if unidad = 'unidad' and new.cantidad <> trunc(new.cantidad) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger movimientos_stock_validar
    before insert on movimientos_stock
    for each row execute function movimientos_stock_validar();

-- Después de insertar un movimiento, suma su cantidad al caché. El UPDATE bloquea la fila hasta el final de la
-- transacción, así dos movimientos simultáneos sobre el mismo artículo y ubicación se ordenan solos. Primero se
-- actualiza y solo si no hay fila se inserta: un INSERT ... ON CONFLICT controlaría el CHECK de no negativo sobre
-- la fila propuesta (la cantidad del movimiento) antes de resolver el conflicto, y rechazaría toda salida.
create function movimientos_stock_actualizar_cantidad() returns trigger
language plpgsql as $$
begin
    update stock_articulos
    set cantidad_actual = cantidad_actual + new.cantidad, updated_at = now()
    where articulo_id = new.articulo_id and ubicacion_stock_id = new.ubicacion_stock_id;
    if not found then
        -- primer movimiento del artículo en la ubicación; si es una salida, el CHECK la rechaza. Si otra
        -- transacción insertó la fila al mismo tiempo, se suma a la suya.
        insert into stock_articulos (articulo_id, ubicacion_stock_id, cantidad_actual)
        values (new.articulo_id, new.ubicacion_stock_id, new.cantidad)
        on conflict (articulo_id, ubicacion_stock_id)
            do update set cantidad_actual = stock_articulos.cantidad_actual + excluded.cantidad_actual,
                          updated_at = now();
    end if;
    return new;
end;
$$;

create trigger movimientos_stock_actualizar_cantidad
    after insert on movimientos_stock
    for each row execute function movimientos_stock_actualizar_cantidad();

-- La cantidad del caché solo la cambia el trigger de movimientos (que corre a profundidad 2). Un INSERT o UPDATE
-- directo puede cargar mínimo y máximo, pero no la cantidad.
create function stock_articulos_validar() returns trigger
language plpgsql as $$
begin
    if tg_op = 'INSERT' or new.articulo_id <> old.articulo_id or new.ubicacion_stock_id <> old.ubicacion_stock_id then
        perform stock_articulo_valido_en_ubicacion(new.articulo_id, new.ubicacion_stock_id);
    end if;
    if pg_trigger_depth() = 1
            and ((tg_op = 'INSERT' and new.cantidad_actual <> 0)
                 or (tg_op = 'UPDATE' and new.cantidad_actual <> old.cantidad_actual)) then
        raise exception 'La cantidad de stock no se edita: es la suma de los movimientos.'
            using errcode = 'insufficient_privilege';
    end if;
    return new;
end;
$$;

create trigger stock_articulos_validar
    before insert or update on stock_articulos
    for each row execute function stock_articulos_validar();

-- Los movimientos no se modifican ni se borran, igual que la auditoría (V2): un error se corrige con otro
-- movimiento.
create function movimientos_stock_inmutable() returns trigger
language plpgsql as $$
begin
    raise exception 'Los movimientos de stock no se pueden modificar ni borrar (operación % rechazada).', tg_op
        using errcode = 'insufficient_privilege';
end;
$$;

create trigger movimientos_stock_sin_update_ni_delete
    before update or delete on movimientos_stock
    for each row execute function movimientos_stock_inmutable();

create trigger movimientos_stock_sin_truncate
    before truncate on movimientos_stock
    for each statement execute function movimientos_stock_inmutable();
