-- Etapa 3, módulo 1: clientes de cada ámbito. Ver docs/modelo-datos.dbml.

create table clientes (
    id                          bigint generated by default as identity primary key,
    ambito_id                   bigint        not null references ambitos (id),
    nombre                      varchar(200),
    razon_social                varchar(200),
    documento_tipo              varchar(4)    check (documento_tipo in ('cuit', 'dni')),
    documento_numero            varchar(11),
    condicion_iva               varchar(30)   not null default 'consumidor_final' check (condicion_iva in
                                    ('responsable_inscripto', 'monotributo', 'exento', 'consumidor_final')),
    telefono                    varchar(50),
    email                       varchar(255),
    direccion                   varchar(255),
    cuenta_corriente_habilitada boolean       not null default false,
    limite_credito              numeric(14,2) check (limite_credito >= 0),
    lista_precios_id            bigint        references listas_precios (id),
    plazo_pago_dias             integer       check (plazo_pago_dias >= 0),
    ambito_representado_id      bigint        references ambitos (id),
    activo                      boolean       not null default true,
    created_at                  timestamptz   not null default now(),
    updated_at                  timestamptz   not null default now(),
    constraint clientes_nombre_o_razon_social
        check (nullif(trim(nombre), '') is not null or nullif(trim(razon_social), '') is not null),
    -- Con coalesce: una comparación con null daría null, y un CHECK con null no falla.
    constraint clientes_documento_valido check (coalesce(
        (documento_tipo is null and documento_numero is null)
        or (documento_tipo = 'cuit' and documento_numero ~ '^[0-9]{11}$')
        or (documento_tipo = 'dni' and documento_numero ~ '^[0-9]{7,8}$'), false)),
    constraint clientes_cuenta_corriente_con_documento
        check (not cuenta_corriente_habilitada or documento_numero is not null),
    -- La cuenta de un local con la fábrica no tiene límite, solo plazo.
    constraint clientes_local_sin_limite
        check (ambito_representado_id is null or (cuenta_corriente_habilitada and limite_credito is null))
);

-- Sin los clientes que representan a un local: dos locales pueden compartir entidad fiscal (y CUIT).
create unique index uq_clientes_documento on clientes (ambito_id, documento_tipo, documento_numero)
    where documento_numero is not null and ambito_representado_id is null;
create unique index uq_clientes_local_representado on clientes (ambito_representado_id)
    where ambito_representado_id is not null;
create index ix_clientes_ambito on clientes (ambito_id, lower(coalesce(nombre, razon_social)));

-- El ámbito y el local representado no cambian; la lista es del mismo ámbito; el cliente que representa a un
-- local es de la fábrica.
create function clientes_validar() returns trigger
language plpgsql as $$
begin
    if tg_op = 'UPDATE' and (new.ambito_id <> old.ambito_id
            or new.ambito_representado_id is distinct from old.ambito_representado_id) then
        raise exception 'El ámbito de un cliente y el local que representa no cambian.'
            using errcode = 'check_violation';
    end if;
    if new.lista_precios_id is not null
            and (select ambito_id from listas_precios where id = new.lista_precios_id) <> new.ambito_id then
        raise exception 'La lista de precios % no es del ámbito del cliente.', new.lista_precios_id
            using errcode = 'check_violation';
    end if;
    if new.ambito_representado_id is not null and (
            (select tipo from ambitos where id = new.ambito_id) <> 'fabrica'
            or (select tipo from ambitos where id = new.ambito_representado_id) <> 'local') then
        raise exception 'Solo la fábrica tiene clientes que representan a un local.'
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger clientes_validar
    before insert or update on clientes
    for each row execute function clientes_validar();

-- Los clientes no se borran: se desactivan.
create function clientes_sin_borrado() returns trigger
language plpgsql as $$
begin
    raise exception 'Los clientes no se borran: se desactivan.' using errcode = 'insufficient_privilege';
end;
$$;

create trigger clientes_sin_delete
    before delete on clientes
    for each row execute function clientes_sin_borrado();

create trigger clientes_sin_truncate
    before truncate on clientes
    for each statement execute function clientes_sin_borrado();

-- Cada local es cliente de la fábrica, con los datos del local y de su entidad fiscal. La base lo crea al dar
-- de alta un local (si ya hay fábrica) o la fábrica (para los locales que ya existan), y lo mantiene al día.
create function clientes_crear_locales(fabrica bigint, local bigint) returns void
language plpgsql as $$
begin
    insert into clientes (ambito_id, nombre, razon_social, documento_tipo, documento_numero, condicion_iva,
                          cuenta_corriente_habilitada, ambito_representado_id)
    select fabrica, a.nombre, e.razon_social, 'cuit', e.cuit, e.condicion_iva, true, a.id
    from ambitos a join entidades_fiscales e on e.id = a.entidad_fiscal_id
    where a.tipo = 'local' and (local is null or a.id = local)
      and not exists (select 1 from clientes c where c.ambito_representado_id = a.id);
end;
$$;

create function ambitos_cliente_de_fabrica() returns trigger
language plpgsql as $$
declare
    fabrica bigint;
begin
    if new.tipo = 'fabrica' then
        perform clientes_crear_locales(new.id, null);
    else
        select id into fabrica from ambitos where tipo = 'fabrica';
        if fabrica is not null then
            perform clientes_crear_locales(fabrica, new.id);
        end if;
    end if;
    return new;
end;
$$;

create trigger ambitos_cliente_de_fabrica
    after insert on ambitos
    for each row execute function ambitos_cliente_de_fabrica();

create function ambitos_actualizar_cliente() returns trigger
language plpgsql as $$
begin
    if new.nombre <> old.nombre then
        update clientes set nombre = new.nombre, updated_at = now() where ambito_representado_id = new.id;
    end if;
    return new;
end;
$$;

create trigger ambitos_actualizar_cliente
    after update on ambitos
    for each row execute function ambitos_actualizar_cliente();

create function entidades_fiscales_actualizar_clientes() returns trigger
language plpgsql as $$
begin
    if new.razon_social <> old.razon_social or new.cuit <> old.cuit or new.condicion_iva <> old.condicion_iva then
        update clientes c
        set razon_social = new.razon_social, documento_numero = new.cuit, condicion_iva = new.condicion_iva,
            updated_at = now()
        from ambitos a
        where a.id = c.ambito_representado_id and a.entidad_fiscal_id = new.id;
    end if;
    return new;
end;
$$;

create trigger entidades_fiscales_actualizar_clientes
    after update on entidades_fiscales
    for each row execute function entidades_fiscales_actualizar_clientes();

