-- Etapa 2, módulo 4: conteos físicos de stock. Ver docs/modelo-datos.dbml.

create table conteos_stock (
    id                 bigint generated by default as identity primary key,
    ubicacion_stock_id bigint      not null references ubicaciones_stock (id),
    usuario_id         bigint      not null references usuarios (id),
    fecha              date        not null,
    estado             varchar(10) not null default 'abierto' check (estado in ('abierto', 'cerrado', 'anulado')),
    observaciones      text,
    cerrado_at         timestamptz,
    anulado_at         timestamptz,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),
    check ((estado = 'abierto' and cerrado_at is null and anulado_at is null)
        or (estado = 'cerrado' and cerrado_at is not null and anulado_at is null)
        or (estado = 'anulado' and anulado_at is not null and cerrado_at is null))
);

-- Un solo conteo abierto por ubicación.
create unique index uq_conteos_stock_abierto on conteos_stock (ubicacion_stock_id) where estado = 'abierto';
create index ix_conteos_stock_ubicacion on conteos_stock (ubicacion_stock_id, id desc);

-- Un conteo cerrado o anulado no se modifica; uno abierto no cambia de ubicación. Ningún conteo se borra: se anula.
create function conteos_stock_proteger() returns trigger
language plpgsql as $$
begin
    if tg_op = 'UPDATE' and old.estado = 'abierto' and new.ubicacion_stock_id = old.ubicacion_stock_id then
        return new;
    end if;
    if tg_op = 'UPDATE' and old.estado = 'abierto' then
        raise exception 'Un conteo no cambia de ubicación.' using errcode = 'insufficient_privilege';
    end if;
    if tg_op = 'UPDATE' then
        raise exception 'El conteo % está %: no se puede modificar.', old.id, old.estado
            using errcode = 'insufficient_privilege';
    end if;
    raise exception 'Los conteos no se borran: se anulan (operación % rechazada).', tg_op
        using errcode = 'insufficient_privilege';
end;
$$;

create trigger conteos_stock_proteger
    before update or delete on conteos_stock
    for each row execute function conteos_stock_proteger();

create trigger conteos_stock_sin_truncate
    before truncate on conteos_stock
    for each statement execute function conteos_stock_proteger();

create table detalle_conteo (
    id               bigint generated by default as identity primary key,
    conteo_id        bigint        not null references conteos_stock (id),
    articulo_id      bigint        not null references articulos (id),
    cantidad_sistema numeric(14,3) check (cantidad_sistema >= 0),
    cantidad_contada numeric(14,3) not null check (cantidad_contada >= 0),
    created_at       timestamptz   not null default now(),
    updated_at       timestamptz   not null default now(),
    unique (conteo_id, articulo_id)
);

-- El detalle solo se carga, cambia o quita mientras el conteo está abierto. Solo se cuentan artículos que el
-- ámbito de la ubicación ve, y lo que se mide en unidades se cuenta en cantidades enteras.
create function detalle_conteo_validar() returns trigger
language plpgsql as $$
declare
    fila      detalle_conteo;
    estado_c  varchar;
    ubicacion bigint;
    unidad    varchar;
begin
    fila := case when tg_op = 'DELETE' then old else new end;
    select estado, ubicacion_stock_id into estado_c, ubicacion from conteos_stock where id = fila.conteo_id;
    if estado_c <> 'abierto' then
        raise exception 'El conteo % está %: su detalle no se puede modificar.', fila.conteo_id, estado_c
            using errcode = 'insufficient_privilege';
    end if;
    if tg_op = 'DELETE' then
        return old;
    end if;
    if tg_op = 'UPDATE' and (new.conteo_id <> old.conteo_id or new.articulo_id <> old.articulo_id) then
        raise exception 'Un renglón de conteo no cambia de conteo ni de artículo.' using errcode = 'check_violation';
    end if;
    perform stock_articulo_valido_en_ubicacion(new.articulo_id, ubicacion);
    select unidad_medida into unidad from articulos where id = new.articulo_id;
    if unidad = 'unidad' and new.cantidad_contada <> trunc(new.cantidad_contada) then
        raise exception 'La cantidad contada de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger detalle_conteo_validar
    before insert or update or delete on detalle_conteo
    for each row execute function detalle_conteo_validar();

-- Los movimientos de un conteo apuntan a él, y solo ellos. Agregar la columna no modifica filas, así que los
-- triggers de inmutabilidad de V6 siguen igual.
alter table movimientos_stock add column conteo_id bigint references conteos_stock (id);
alter table movimientos_stock add constraint movimientos_stock_conteo_segun_tipo
    check ((tipo = 'conteo') = (conteo_id is not null));
create index ix_movimientos_stock_conteo on movimientos_stock (conteo_id) where conteo_id is not null;

-- Además de lo que ya validaba (V6), el movimiento de un conteo es de la ubicación del conteo.
create or replace function movimientos_stock_validar() returns trigger
language plpgsql as $$
declare
    unidad varchar;
begin
    perform stock_articulo_valido_en_ubicacion(new.articulo_id, new.ubicacion_stock_id);
    select unidad_medida into unidad from articulos where id = new.articulo_id;
    if unidad = 'unidad' and new.cantidad <> trunc(new.cantidad) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    if new.conteo_id is not null
            and not exists (select 1 from conteos_stock
                            where id = new.conteo_id and ubicacion_stock_id = new.ubicacion_stock_id) then
        raise exception 'El movimiento del conteo % debe ser de la ubicación del conteo.', new.conteo_id
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;
