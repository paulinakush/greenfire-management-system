-- Etapa 3, módulo 3: comprobantes no fiscales (letra X) y su numeración. Ver docs/modelo-datos.dbml.
--
-- Garantías de la base, aunque se escriba por fuera de la aplicación:
-- - La numeración es correlativa por punto de venta, tipo y letra, sin huecos ni repetidos:
--   * punto_venta_comprobantes.ultimo_numero solo avanza de a uno, y solo si el número anterior ya tiene su
--     comprobante;
--   * al confirmar la transacción, el último número tiene su comprobante (si la emisión se revierte, el número
--     vuelve atrás con ella);
--   * un comprobante solo se inserta con el último número tomado de su punto de venta, tipo y letra;
--   * el índice único (punto_venta_id, tipo, letra, numero) es la garantía final.
-- - Un comprobante emitido no se modifica ni se borra: solo pasa a anulado, una vez. Su detalle se carga en la
--   misma transacción que lo emite y después no cambia.

-- ---------------------------------------------------------------------------
-- Tipos nuevos y número por punto de venta, tipo y letra
-- ---------------------------------------------------------------------------

alter table punto_venta_comprobantes drop constraint punto_venta_comprobantes_tipo_check;
alter table punto_venta_comprobantes add constraint punto_venta_comprobantes_tipo_check check (tipo in
    ('factura', 'nota_credito', 'nota_debito', 'remito', 'recibo', 'presupuesto', 'comprobante_venta'));
-- El comprobante de venta es solo X; la factura nunca es X (las notas de crédito y de débito pueden ser X o fiscales).
alter table punto_venta_comprobantes add constraint punto_venta_comprobantes_letra_segun_tipo
    check ((tipo <> 'comprobante_venta' or letra = 'X') and (tipo <> 'factura' or letra <> 'X'));
alter table punto_venta_comprobantes
    add column ultimo_numero integer not null default 0 check (ultimo_numero >= 0);

create table comprobantes (
    id                      bigint generated by default as identity primary key,
    tipo                    varchar(20)   not null check (tipo in
                                ('factura', 'nota_credito', 'nota_debito', 'remito', 'recibo', 'presupuesto',
                                 'comprobante_venta')),
    letra                   varchar(1)    not null check (letra in ('A', 'B', 'C', 'X')),
    punto_venta_id          bigint        not null references puntos_venta (id),
    numero                  integer       not null check (numero between 1 and 99999999),
    -- emisor, copiado al emitir
    emisor_razon_social     varchar(200)  not null,
    emisor_cuit             varchar(11)   not null,
    emisor_condicion_iva    varchar(30)   not null check (emisor_condicion_iva in
                                ('responsable_inscripto', 'monotributo', 'exento', 'consumidor_final')),
    emisor_domicilio_fiscal varchar(255),
    emisor_nombre           varchar(120)  not null,
    emisor_direccion        varchar(255),
    -- receptor, copiado al emitir
    cliente_id              bigint        references clientes (id),
    receptor_razon_social   varchar(200),
    receptor_documento_tipo varchar(4)    check (receptor_documento_tipo in ('cuit', 'dni')),
    receptor_documento      varchar(11),
    receptor_condicion_iva  varchar(30)   not null default 'consumidor_final' check (receptor_condicion_iva in
                                ('responsable_inscripto', 'monotributo', 'exento', 'consumidor_final')),
    receptor_domicilio      varchar(255),
    usuario_id              bigint        not null references usuarios (id),
    fecha                   timestamptz   not null default now(),
    fecha_vencimiento       date,
    estado                  varchar(10)   not null default 'emitido' check (estado in ('emitido', 'anulado')),
    anulado_por_usuario_id  bigint        references usuarios (id),
    anulado_at              timestamptz,
    motivo_anulacion        text,
    comprobante_asociado_id bigint        references comprobantes (id),
    precios_con_iva         boolean       not null,
    neto                    numeric(14,2) not null check (neto >= 0),
    iva                     numeric(14,2) not null check (iva >= 0),
    total                   numeric(14,2) not null check (total >= 0),
    arca_estado             varchar(10)   check (arca_estado in ('pendiente', 'autorizado', 'rechazado')),
    cae                     varchar(20),
    cae_vence               date,
    observaciones           text,
    created_at              timestamptz   not null default now(),
    updated_at              timestamptz   not null default now(),
    constraint uq_comprobantes_numero unique (punto_venta_id, tipo, letra, numero),
    constraint comprobantes_letra_segun_tipo
        check ((tipo <> 'comprobante_venta' or letra = 'X') and (tipo <> 'factura' or letra <> 'X')),
    -- Los X no pasan por ARCA; los fiscales (etapa 6) sí.
    constraint comprobantes_arca_segun_letra check (
        (letra = 'X' and arca_estado is null and cae is null and cae_vence is null)
        or (letra <> 'X' and arca_estado is not null)),
    constraint comprobantes_documento_receptor
        check ((receptor_documento_tipo is null) = (receptor_documento is null)),
    constraint comprobantes_total_neto_mas_iva check (total = neto + iva),
    -- Solo el emisor que discrimina IVA tiene IVA; para los demás, los precios son finales.
    constraint comprobantes_iva_segun_emisor
        check (emisor_condicion_iva = 'responsable_inscripto' or (iva = 0 and precios_con_iva)),
    constraint comprobantes_asociado_segun_tipo
        check (comprobante_asociado_id is null or tipo in ('nota_credito', 'nota_debito')),
    -- Con coalesce: un CHECK que da null no falla.
    constraint comprobantes_anulacion_coherente check (coalesce(
        (estado = 'emitido' and anulado_por_usuario_id is null and anulado_at is null and motivo_anulacion is null)
        or (estado = 'anulado' and anulado_por_usuario_id is not null and anulado_at is not null
            and length(trim(motivo_anulacion)) > 0), false))
);

create index ix_comprobantes_punto_venta on comprobantes (punto_venta_id, fecha desc);
create index ix_comprobantes_cliente on comprobantes (cliente_id) where cliente_id is not null;
create index ix_comprobantes_asociado on comprobantes (comprobante_asociado_id) where comprobante_asociado_id is not null;

create table detalle_comprobante (
    id              bigint generated by default as identity primary key,
    comprobante_id  bigint        not null references comprobantes (id),
    articulo_id     bigint        references articulos (id),
    descripcion     varchar(255)  not null check (length(trim(descripcion)) > 0),
    cantidad        numeric(14,3) not null check (cantidad > 0),
    precio_unitario numeric(14,2) not null check (precio_unitario >= 0),
    alicuota_iva    numeric(5,2)  not null check (alicuota_iva between 0 and 100),
    subtotal        numeric(14,2) not null,
    created_at      timestamptz   not null default now(),
    updated_at      timestamptz   not null default now(),
    constraint detalle_comprobante_subtotal check (subtotal = round(cantidad * precio_unitario, 2))
);

create index ix_detalle_comprobante on detalle_comprobante (comprobante_id);

-- ---------------------------------------------------------------------------
-- Numeración
-- ---------------------------------------------------------------------------

-- Al agregar un tipo a un punto de venta (o volver a agregarlo), el número sigue desde el último emitido.
-- Después solo avanza de a uno, y solo si el número anterior ya tiene su comprobante.
create function punto_venta_comprobantes_numerar() returns trigger
language plpgsql as $$
begin
    if tg_op = 'INSERT' then
        new.ultimo_numero := coalesce((select max(numero) from comprobantes
                                       where punto_venta_id = new.punto_venta_id and tipo = new.tipo
                                         and letra = new.letra), 0);
        return new;
    end if;

    if (new.punto_venta_id, new.tipo, new.letra) is distinct from (old.punto_venta_id, old.tipo, old.letra) then
        raise exception 'El punto de venta, el tipo y la letra de una numeración no cambian.'
            using errcode = 'insufficient_privilege';
    end if;
    if new.ultimo_numero = old.ultimo_numero then
        return new;
    end if;
    if new.ultimo_numero <> old.ultimo_numero + 1 then
        raise exception 'La numeración de % % avanza de a uno (de % a %).', old.tipo, old.letra,
            old.ultimo_numero, new.ultimo_numero
            using errcode = 'insufficient_privilege';
    end if;
    if old.ultimo_numero > 0 and not exists (
            select 1 from comprobantes
            where punto_venta_id = old.punto_venta_id and tipo = old.tipo and letra = old.letra
              and numero = old.ultimo_numero) then
        raise exception 'El número % de % % todavía no tiene comprobante: no se saltea.', old.ultimo_numero,
            old.tipo, old.letra
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger punto_venta_comprobantes_numerar
    before insert or update on punto_venta_comprobantes
    for each row execute function punto_venta_comprobantes_numerar();

-- Al confirmar: el último número tomado tiene su comprobante. Si la emisión falla y se revierte, el número no se
-- consume, porque el avance se revierte con ella.
create function punto_venta_comprobantes_verificar_numero() returns trigger
language plpgsql as $$
declare
    fila record;
begin
    select punto_venta_id, tipo, letra, ultimo_numero into fila from punto_venta_comprobantes where id = new.id;
    if found and fila.ultimo_numero > 0 and not exists (
            select 1 from comprobantes
            where punto_venta_id = fila.punto_venta_id and tipo = fila.tipo and letra = fila.letra
              and numero = fila.ultimo_numero) then
        raise exception 'El número % de % % quedó sin comprobante.', fila.ultimo_numero, fila.tipo, fila.letra
            using errcode = 'check_violation';
    end if;
    return null;
end;
$$;

create constraint trigger punto_venta_comprobantes_numero_usado
    after update of ultimo_numero on punto_venta_comprobantes deferrable initially deferred
    for each row when (new.ultimo_numero <> old.ultimo_numero)
    execute function punto_venta_comprobantes_verificar_numero();

-- ---------------------------------------------------------------------------
-- Comprobantes: se emiten con el número tomado y solo se anulan
-- ---------------------------------------------------------------------------

create function comprobantes_validar() returns trigger
language plpgsql as $$
declare
    pv      record;
    entidad record;
begin
    if tg_op = 'DELETE' or tg_op = 'TRUNCATE' then
        raise exception 'Los comprobantes no se borran: se anulan (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;

    if tg_op = 'INSERT' then
        if new.estado <> 'emitido' then
            raise exception 'Un comprobante nace emitido.' using errcode = 'check_violation';
        end if;
        select ambito_id, entidad_fiscal_id, activo into pv from puntos_venta where id = new.punto_venta_id;
        if not pv.activo then
            raise exception 'El punto de venta % está desactivado.', new.punto_venta_id
                using errcode = 'check_violation';
        end if;
        if not exists (select 1 from punto_venta_comprobantes
                       where punto_venta_id = new.punto_venta_id and tipo = new.tipo and letra = new.letra
                         and ultimo_numero = new.numero) then
            raise exception 'El número % no es el último tomado para % % en el punto de venta %.', new.numero,
                new.tipo, new.letra, new.punto_venta_id
                using errcode = 'check_violation';
        end if;
        select razon_social, cuit, condicion_iva into entidad from entidades_fiscales where id = pv.entidad_fiscal_id;
        if (new.emisor_razon_social, new.emisor_cuit, new.emisor_condicion_iva)
                is distinct from (entidad.razon_social, entidad.cuit, entidad.condicion_iva) then
            raise exception 'Los datos del emisor no son los de la entidad fiscal del punto de venta.'
                using errcode = 'check_violation';
        end if;
        if new.cliente_id is not null
                and not exists (select 1 from clientes where id = new.cliente_id and ambito_id = pv.ambito_id) then
            raise exception 'El cliente % no es del ámbito del punto de venta.', new.cliente_id
                using errcode = 'check_violation';
        end if;
        if new.comprobante_asociado_id is not null and not exists (
                select 1 from comprobantes c join puntos_venta p on p.id = c.punto_venta_id
                where c.id = new.comprobante_asociado_id and p.entidad_fiscal_id = pv.entidad_fiscal_id) then
            raise exception 'El comprobante asociado es de otra entidad fiscal.' using errcode = 'check_violation';
        end if;
        -- Marca, solo para esta transacción, que el comprobante se está emitiendo: su detalle se puede cargar
        -- hasta que termine. Una variable local (y no xmin) respeta los savepoints.
        perform set_config('greenfire.comprobante_emitiendo_' || new.id, 'si', true);
        return new;
    end if;

    -- UPDATE: solo emitido -> anulado, sin tocar nada más.
    if old.estado <> 'emitido' then
        raise exception 'El comprobante % está anulado: no se modifica.', old.id
            using errcode = 'insufficient_privilege';
    end if;
    if new.estado <> 'anulado' then
        raise exception 'Un comprobante emitido no se modifica: solo se anula (comprobante %).', old.id
            using errcode = 'insufficient_privilege';
    end if;
    if (to_jsonb(new) - array['estado', 'anulado_por_usuario_id', 'anulado_at', 'motivo_anulacion', 'updated_at'])
            <> (to_jsonb(old) - array['estado', 'anulado_por_usuario_id', 'anulado_at', 'motivo_anulacion', 'updated_at']) then
        raise exception 'Al anular el comprobante % no cambia nada más.', old.id
            using errcode = 'insufficient_privilege';
    end if;
    return new;
end;
$$;

create trigger comprobantes_validar
    before insert or update or delete on comprobantes
    for each row execute function comprobantes_validar();

create trigger comprobantes_sin_truncate
    before truncate on comprobantes
    for each statement execute function comprobantes_validar();

-- El detalle se carga en la misma transacción que emite el comprobante (con la marca que deja
-- comprobantes_validar); después no cambia ni se borra.
create function detalle_comprobante_validar() returns trigger
language plpgsql as $$
begin
    if tg_op <> 'INSERT' then
        raise exception 'El detalle de un comprobante no se modifica ni se borra (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;
    if coalesce(current_setting('greenfire.comprobante_emitiendo_' || new.comprobante_id, true), '') <> 'si'
            or not exists (select 1 from comprobantes where id = new.comprobante_id and estado = 'emitido') then
        raise exception 'El detalle del comprobante % se carga al emitirlo.', new.comprobante_id
            using errcode = 'insufficient_privilege';
    end if;
    return new;
end;
$$;

create trigger detalle_comprobante_validar
    before insert or update or delete on detalle_comprobante
    for each row execute function detalle_comprobante_validar();

create trigger detalle_comprobante_sin_truncate
    before truncate on detalle_comprobante
    for each statement execute function detalle_comprobante_validar();

-- Al confirmar, cada comprobante tiene al menos un renglón, y la suma de los subtotales es su total (precios con
-- IVA) o su neto (precios sin IVA).
create function comprobantes_verificar_total() returns trigger
language plpgsql as $$
declare
    id_comprobante bigint;
    renglones      integer;
    suma           numeric;
    c              record;
begin
    id_comprobante := case when tg_table_name = 'comprobantes' then (to_jsonb(new) ->> 'id')::bigint
                           else (to_jsonb(new) ->> 'comprobante_id')::bigint end;
    select count(*), coalesce(sum(subtotal), 0) into renglones, suma
    from detalle_comprobante where comprobante_id = id_comprobante;
    select precios_con_iva, neto, total into c from comprobantes where id = id_comprobante;
    if renglones = 0 then
        raise exception 'El comprobante % no tiene renglones.', id_comprobante using errcode = 'check_violation';
    end if;
    if suma <> (case when c.precios_con_iva then c.total else c.neto end) then
        raise exception 'El % del comprobante % no es la suma de sus renglones (%).',
            case when c.precios_con_iva then 'total' else 'neto' end, id_comprobante, suma
            using errcode = 'check_violation';
    end if;
    return null;
end;
$$;

create constraint trigger comprobantes_total
    after insert on comprobantes deferrable initially deferred
    for each row execute function comprobantes_verificar_total();

create constraint trigger detalle_comprobante_total
    after insert on detalle_comprobante deferrable initially deferred
    for each row execute function comprobantes_verificar_total();
