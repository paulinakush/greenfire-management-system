-- Etapa 3, módulo 5: ventas presenciales de los locales y ventas de la fábrica a sus mayoristas.
-- Ver docs/modelo-datos.dbml.
--
-- Garantías de la base, aunque se escriba por fuera de la aplicación:
-- - Una venta nace confirmada, con su comprobante de venta del mismo ámbito y por el mismo total, y en un local
--   con la caja abierta. Después solo pasa a anulada, una vez y con motivo, si no tiene devoluciones.
-- - Los renglones de una venta y de una devolución se cargan con ella, en la misma transacción, y no cambian.
-- - Lo devuelto de un renglón nunca supera lo vendido.
-- - Los movimientos de stock de una venta son de sus renglones: la venta saca lo vendido, una vez; la anulación
--   y la devolución suman, sin pasarse de lo vendido.

