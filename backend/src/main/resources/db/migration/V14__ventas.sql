-- ---------------------------------------------------------------------------
-- Ventas
-- ---------------------------------------------------------------------------

create table ventas (
    id                     bigint generated by default as identity primary key,
    ambito_id              bigint        not null references ambitos (id),
    usuario_id             bigint        not null references usuarios (id),
    cliente_id             bigint        references clientes (id),
    sesion_caja_id         bigint        references sesiones_caja (id),
    fecha_hora             timestamptz   not null default now(),
    medio_pago             varchar(20)   not null
                               check (medio_pago in ('efectivo', 'transferencia', 'billetera_virtual', 'cuenta_corriente')),
    fecha_cobro            date,
    subtotal               numeric(14,2) not null check (subtotal >= 0),
    porcentaje_descuento   numeric(5,2)  not null default 0 check (porcentaje_descuento between 0 and 100),
    descuento              numeric(14,2) not null check (descuento >= 0),
    total                  numeric(14,2) not null check (total >= 0),
    estado                 varchar(10)   not null default 'confirmada' check (estado in ('confirmada', 'anulada')),
    comprobante_id         bigint        not null references comprobantes (id),
    anulada_por_usuario_id bigint        references usuarios (id),
    anulada_at             timestamptz,
    motivo_anulacion       text,
    created_at             timestamptz   not null default now(),
    updated_at             timestamptz   not null default now(),
    constraint ventas_total_con_descuento check (total = subtotal - descuento),
    constraint ventas_anulacion_coherente check (coalesce(
        (estado = 'confirmada' and anulada_por_usuario_id is null and anulada_at is null and motivo_anulacion is null)
        or (estado = 'anulada' and anulada_por_usuario_id is not null and anulada_at is not null
            and length(trim(motivo_anulacion)) > 0), false)),
    -- la cuenta corriente no pasa por la caja
    constraint ventas_cuenta_corriente_sin_caja check (medio_pago <> 'cuenta_corriente' or sesion_caja_id is null)
);

create unique index uq_ventas_comprobante on ventas (comprobante_id);
create index ix_ventas_ambito on ventas (ambito_id, fecha_hora desc);
create index ix_ventas_cliente on ventas (cliente_id) where cliente_id is not null;
create index ix_ventas_sesion_caja on ventas (sesion_caja_id) where sesion_caja_id is not null;

create table detalle_ventas (
    id                 bigint generated by default as identity primary key,
    venta_id           bigint        not null references ventas (id),
    articulo_id        bigint        not null references articulos (id),
    ubicacion_stock_id bigint        not null references ubicaciones_stock (id),
    cantidad           numeric(14,3) not null check (cantidad > 0),
    precio_lista       numeric(14,2) not null check (precio_lista >= 0),
    precio_unitario    numeric(14,2) not null check (precio_unitario >= 0),
    alicuota_iva       numeric(5,2)  not null check (alicuota_iva between 0 and 100),
    costo_unitario     numeric(14,2) check (costo_unitario >= 0),
    subtotal           numeric(14,2) not null,
    created_at         timestamptz   not null default now(),
    updated_at         timestamptz   not null default now(),
    constraint detalle_ventas_descuento check (precio_unitario <= precio_lista),
    -- el mismo redondeo que el comprobante
    constraint detalle_ventas_subtotal check (subtotal = round(cantidad * precio_unitario, 2))
);

create unique index uq_detalle_ventas_renglon on detalle_ventas (venta_id, articulo_id, ubicacion_stock_id);

create table devoluciones_venta (
    id              bigint generated by default as identity primary key,
