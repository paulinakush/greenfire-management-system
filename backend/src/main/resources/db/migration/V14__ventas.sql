    id               bigint generated by default as identity primary key,
    devolucion_id    bigint        not null references devoluciones_venta (id),
    detalle_venta_id bigint        not null references detalle_ventas (id),
    cantidad         numeric(14,3) not null check (cantidad > 0),
    subtotal         numeric(14,2) not null check (subtotal >= 0),
    created_at       timestamptz   not null default now(),
    updated_at       timestamptz   not null default now()
);

create unique index uq_detalle_devoluciones_venta_renglon on detalle_devoluciones_venta (devolucion_id, detalle_venta_id);
