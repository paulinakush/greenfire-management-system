-- ---------------------------------------------------------------------------
-- Ventas: nacen confirmadas y solo pasan a anuladas
-- ---------------------------------------------------------------------------

create function ventas_validar() returns trigger
language plpgsql as $$
declare
    tipo_ambito varchar;
    c           record;
begin
    if tg_op = 'DELETE' or tg_op = 'TRUNCATE' then
        raise exception 'Las ventas no se borran: se anulan (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;

    if tg_op = 'INSERT' then
        if new.estado <> 'confirmada' then
            raise exception 'Una venta nace confirmada.' using errcode = 'check_violation';
        end if;
        select tipo into tipo_ambito from ambitos where id = new.ambito_id;
        if new.cliente_id is not null and not exists (
                select 1 from clientes where id = new.cliente_id and ambito_id = new.ambito_id
                                         and ambito_representado_id is null) then
            raise exception 'El cliente de la venta debe ser del mismo ámbito, y no el de un local: a los locales se les vende con entregas.'
                using errcode = 'check_violation';
        end if;
        if tipo_ambito = 'local' then
            if new.fecha_cobro is not null then
                raise exception 'La fecha de cobro es de las ventas de la fábrica: en un local, el cobro va a la caja.'
                    using errcode = 'check_violation';
            end if;
            if new.medio_pago <> 'cuenta_corriente' and not exists (
                    select 1 from sesiones_caja
                    where id = new.sesion_caja_id and ambito_id = new.ambito_id and estado = 'abierta') then
                raise exception 'Una venta de un local se cobra en su caja abierta.' using errcode = 'check_violation';
            end if;
        else
            if new.cliente_id is null then
                raise exception 'Una venta de la fábrica es siempre a un cliente mayorista.' using errcode = 'check_violation';
            end if;
            if new.sesion_caja_id is not null then
                raise exception 'La fábrica no tiene caja.' using errcode = 'check_violation';
            end if;
            if (new.medio_pago = 'cuenta_corriente') <> (new.fecha_cobro is null) then
                raise exception 'Una venta de la fábrica lleva la fecha de cobro, salvo a cuenta corriente.'
                    using errcode = 'check_violation';
            end if;
        end if;
        select co.tipo, co.estado, co.total, co.cliente_id, pv.ambito_id into c
        from comprobantes co join puntos_venta pv on pv.id = co.punto_venta_id where co.id = new.comprobante_id;
        if c.tipo is distinct from 'comprobante_venta' or c.ambito_id <> new.ambito_id or c.estado <> 'emitido'
                or c.total <> new.total or c.cliente_id is distinct from new.cliente_id then
            raise exception 'El comprobante de la venta debe ser un comprobante de venta emitido del mismo ámbito, con el mismo cliente y el mismo total.'
                using errcode = 'check_violation';
        end if;
        -- marca para los renglones y los movimientos de stock, que se cargan en esta misma transacción
        perform set_config('greenfire.venta_creando_' || new.id, 'si', true);
        return new;
    end if;

    -- UPDATE: solo la anulación, una vez
    if old.estado <> 'confirmada' or new.estado <> 'anulada' then
        raise exception 'La venta % está %: solo se anula una venta confirmada.', old.id, old.estado
            using errcode = 'insufficient_privilege';
    end if;
    if (to_jsonb(new) - array['estado', 'anulada_por_usuario_id', 'anulada_at', 'motivo_anulacion', 'updated_at'])
            <> (to_jsonb(old) - array['estado', 'anulada_por_usuario_id', 'anulada_at', 'motivo_anulacion', 'updated_at']) then
        raise exception 'Al anular la venta % solo cambian el estado y los datos de la anulación.', old.id
            using errcode = 'insufficient_privilege';
    end if;
    if exists (select 1 from devoluciones_venta where venta_id = old.id) then
        raise exception 'La venta % tiene devoluciones: no se anula, se devuelve el resto.', old.id
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger ventas_validar
    before insert or update or delete on ventas
    for each row execute function ventas_validar();

create trigger ventas_sin_truncate
    before truncate on ventas
    for each statement execute function ventas_validar();

-- Los renglones se cargan con la venta, en la misma transacción: del ámbito de la venta, nunca insumos, enteros si
-- el artículo se mide en unidades. No se modifican ni se borran.
create function detalle_ventas_validar() returns trigger
language plpgsql as $$
declare
    ambito_venta bigint;
    a            record;
begin
    if tg_op <> 'INSERT' then
        raise exception 'El detalle de una venta no se modifica ni se borra (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;
    if coalesce(current_setting('greenfire.venta_creando_' || new.venta_id, true), '') <> 'si' then
        raise exception 'Los renglones de la venta % se cargan al registrarla.', new.venta_id
            using errcode = 'insufficient_privilege';
    end if;
    select ambito_id into ambito_venta from ventas where id = new.venta_id;
    if not exists (select 1 from ubicaciones_stock where id = new.ubicacion_stock_id and ambito_id = ambito_venta) then
        raise exception 'La ubicación del renglón debe ser del ámbito de la venta.' using errcode = 'check_violation';
    end if;
    perform stock_articulo_valido_en_ubicacion(new.articulo_id, new.ubicacion_stock_id);
    select tipo, unidad_medida into a from articulos where id = new.articulo_id;
    if a.tipo = 'insumo' then
        raise exception 'Los insumos no se venden.' using errcode = 'check_violation';
    end if;
    if a.unidad_medida = 'unidad' and new.cantidad <> trunc(new.cantidad) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger detalle_ventas_validar
    before insert or update or delete on detalle_ventas
    for each row execute function detalle_ventas_validar();

create trigger detalle_ventas_sin_truncate
    before truncate on detalle_ventas
    for each statement execute function detalle_ventas_validar();

-- Al confirmar la transacción, cada venta tiene al menos un renglón, su total es la suma de los subtotales y su
-- subtotal, la suma a precio de lista.
create function ventas_verificar_total() returns trigger
language plpgsql as $$
declare
    id_venta  bigint;
    renglones integer;
    suma      numeric;
    suma_lista numeric;
    v         record;
begin
    id_venta := case when tg_table_name = 'ventas' then (to_jsonb(new) ->> 'id')::bigint
                     else (to_jsonb(new) ->> 'venta_id')::bigint end;
    select count(*), coalesce(sum(subtotal), 0), coalesce(sum(round(cantidad * precio_lista, 2)), 0)
        into renglones, suma, suma_lista
    from detalle_ventas where venta_id = id_venta;
    select total, subtotal into v from ventas where id = id_venta;
    if renglones = 0 then
        raise exception 'La venta % no tiene renglones.', id_venta using errcode = 'check_violation';
    end if;
    if suma <> v.total or suma_lista <> v.subtotal then
        raise exception 'El total de la venta % no es la suma de sus renglones.', id_venta
            using errcode = 'check_violation';
    end if;
    return null;
end;
$$;

create constraint trigger ventas_total
    after insert on ventas deferrable initially deferred
    for each row execute function ventas_verificar_total();

create constraint trigger detalle_ventas_total
    after insert on detalle_ventas deferrable initially deferred
    for each row execute function ventas_verificar_total();

-- ---------------------------------------------------------------------------
-- Devoluciones parciales
-- ---------------------------------------------------------------------------

-- De una venta confirmada, con su nota de crédito por el mismo total que referencia al comprobante de la venta. El
-- bloqueo compartido de la venta ordena la devolución con una anulación simultánea.
create function devoluciones_venta_validar() returns trigger
language plpgsql as $$
declare
    v record;
    n record;
begin
    if tg_op <> 'INSERT' then
        raise exception 'Las devoluciones de una venta no se modifican ni se borran (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;
    select estado, ambito_id, comprobante_id, medio_pago into v from ventas where id = new.venta_id for share;
    if v.estado <> 'confirmada' then
        raise exception 'La venta % está %: no admite devoluciones.', new.venta_id, v.estado
            using errcode = 'check_violation';
    end if;
    select tipo, estado, total, comprobante_asociado_id into n from comprobantes where id = new.nota_credito_id;
    if n.tipo is distinct from 'nota_credito' or n.estado <> 'emitido' or n.total <> new.total
            or n.comprobante_asociado_id is distinct from v.comprobante_id then
        raise exception 'La devolución lleva una nota de crédito emitida, por el mismo total, que referencia al comprobante de la venta.'
            using errcode = 'check_violation';
    end if;
    if new.sesion_caja_id is not null and not exists (
            select 1 from sesiones_caja where id = new.sesion_caja_id and ambito_id = v.ambito_id and estado = 'abierta') then
        raise exception 'El dinero de la devolución sale de la caja abierta del local de la venta.'
            using errcode = 'check_violation';
    end if;
    perform set_config('greenfire.devolucion_creando_' || new.id, 'si', true);
    return new;
end;
$$;

create trigger devoluciones_venta_validar
    before insert or update or delete on devoluciones_venta
    for each row execute function devoluciones_venta_validar();

create trigger devoluciones_venta_sin_truncate
    before truncate on devoluciones_venta
    for each statement execute function devoluciones_venta_validar();

-- Los renglones devueltos se cargan con la devolución, son de la misma venta y nunca superan lo vendido. Bloquea
-- el renglón vendido, así dos devoluciones simultáneas se ordenan.
create function detalle_devoluciones_venta_validar() returns trigger
language plpgsql as $$
declare
    d        record;
    devuelto numeric;
begin
    if tg_op <> 'INSERT' then
        raise exception 'El detalle de una devolución no se modifica ni se borra (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;
    if coalesce(current_setting('greenfire.devolucion_creando_' || new.devolucion_id, true), '') <> 'si' then
        raise exception 'Los renglones de la devolución % se cargan al registrarla.', new.devolucion_id
            using errcode = 'insufficient_privilege';
    end if;
    select dv.cantidad, dv.precio_unitario, dv.venta_id, a.unidad_medida into d
    from detalle_ventas dv join articulos a on a.id = dv.articulo_id
    where dv.id = new.detalle_venta_id for update of dv;
    if d.venta_id is distinct from (select venta_id from devoluciones_venta where id = new.devolucion_id) then
        raise exception 'El renglón devuelto debe ser de la venta de la devolución.' using errcode = 'check_violation';
    end if;
    if d.unidad_medida = 'unidad' and new.cantidad <> trunc(new.cantidad) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    if new.subtotal <> round(new.cantidad * d.precio_unitario, 2) then
        raise exception 'El subtotal devuelto es la cantidad por el precio del renglón vendido.'
            using errcode = 'check_violation';
    end if;
    select coalesce(sum(cantidad), 0) into devuelto from detalle_devoluciones_venta
    where detalle_venta_id = new.detalle_venta_id;
    if devuelto + new.cantidad > d.cantidad then
        raise exception 'Lo devuelto del renglón % supera lo vendido.', new.detalle_venta_id
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger detalle_devoluciones_venta_validar
    before insert or update or delete on detalle_devoluciones_venta
    for each row execute function detalle_devoluciones_venta_validar();

create trigger detalle_devoluciones_venta_sin_truncate
    before truncate on detalle_devoluciones_venta
    for each statement execute function detalle_devoluciones_venta_validar();

create function devoluciones_venta_verificar_total() returns trigger
language plpgsql as $$
declare
    id_devolucion bigint;
    renglones     integer;
    suma          numeric;
begin
    id_devolucion := case when tg_table_name = 'devoluciones_venta' then (to_jsonb(new) ->> 'id')::bigint
                          else (to_jsonb(new) ->> 'devolucion_id')::bigint end;
    select count(*), coalesce(sum(subtotal), 0) into renglones, suma
    from detalle_devoluciones_venta where devolucion_id = id_devolucion;
    if renglones = 0 then
        raise exception 'La devolución % no tiene renglones.', id_devolucion using errcode = 'check_violation';
    end if;
    if suma <> (select total from devoluciones_venta where id = id_devolucion) then
        raise exception 'El total de la devolución % no es la suma de sus renglones.', id_devolucion
            using errcode = 'check_violation';
    end if;
    return null;
end;
$$;

create constraint trigger devoluciones_venta_total
    after insert on devoluciones_venta deferrable initially deferred
    for each row execute function devoluciones_venta_verificar_total();

create constraint trigger detalle_devoluciones_venta_total
    after insert on detalle_devoluciones_venta deferrable initially deferred
    for each row execute function devoluciones_venta_verificar_total();

-- ---------------------------------------------------------------------------
-- Movimientos de stock de las ventas
-- ---------------------------------------------------------------------------

alter table movimientos_stock add column venta_id bigint references ventas (id);
create index ix_movimientos_stock_venta on movimientos_stock (venta_id) where venta_id is not null;

-- La venta exige venta_id; la salida y la recepción de una entrega, entrega_id; la anulación y la devolución, uno
-- de los dos y nunca los dos; los demás tipos, ninguno.
alter table movimientos_stock drop constraint movimientos_stock_entrega_segun_tipo;
alter table movimientos_stock add constraint movimientos_stock_referencia_segun_tipo check (
    case
        when tipo = 'venta' then venta_id is not null and entrega_id is null
        when tipo in ('entrega_salida', 'entrega_recepcion') then entrega_id is not null and venta_id is null
        when tipo in ('anulacion', 'devolucion') then num_nonnulls(entrega_id, venta_id) = 1
        else entrega_id is null and venta_id is null
    end);

-- Igual que en V9, más las reglas de los movimientos de una venta: son de un renglón (su artículo y su ubicación);
-- la venta saca lo vendido, una sola vez y al registrarla; la anulación (de una venta anulada) y la devolución
-- (de una confirmada) suman, sin pasarse de lo vendido. Bloquea el renglón, así dos devoluciones se ordenan.
create or replace function movimientos_stock_validar() returns trigger
language plpgsql as $$
declare
    unidad    varchar;
    origen    bigint;
    destino   bigint;
    ubicacion bigint;
    estado_v  varchar;
    vendida   numeric;
    vuelto    numeric;
begin
    perform stock_articulo_valido_en_ubicacion(new.articulo_id, new.ubicacion_stock_id);
    select unidad_medida into unidad from articulos where id = new.articulo_id;
    if unidad = 'unidad' and new.cantidad <> trunc(new.cantidad) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    if new.conteo_id is not null
            and not exists (select 1 from conteos_stock
                            where id = new.conteo_id and ubicacion_stock_id = new.ubicacion_stock_id) then
        raise exception 'El movimiento del conteo % debe ser de la ubicación del conteo.', new.conteo_id
            using errcode = 'check_violation';
    end if;
    if new.entrega_id is not null then
        select ubicacion_origen_id, ubicacion_destino_id into origen, destino from entregas where id = new.entrega_id;
        ubicacion := case when new.tipo = 'entrega_recepcion' then destino else origen end;
        if ubicacion is distinct from new.ubicacion_stock_id then
            raise exception 'El movimiento de la entrega % no es de la ubicación que corresponde.', new.entrega_id
                using errcode = 'check_violation';
        end if;
        if (new.tipo = 'entrega_salida') <> (new.cantidad < 0) then
            raise exception 'En una entrega, la salida resta y la recepción, la anulación y la devolución suman.'
                using errcode = 'check_violation';
        end if;
        if not exists (select 1 from detalle_entregas
                       where entrega_id = new.entrega_id and articulo_id = new.articulo_id) then
            raise exception 'El artículo no es de la entrega %.', new.entrega_id using errcode = 'check_violation';
        end if;
    end if;
    if new.venta_id is not null then
        select estado into estado_v from ventas where id = new.venta_id;
        select cantidad into vendida from detalle_ventas
        where venta_id = new.venta_id and articulo_id = new.articulo_id and ubicacion_stock_id = new.ubicacion_stock_id
        for update;
        if not found then
            raise exception 'El movimiento no es de un renglón de la venta % (artículo y ubicación).', new.venta_id
                using errcode = 'check_violation';
        end if;
        if new.tipo = 'venta' then
            if coalesce(current_setting('greenfire.venta_creando_' || new.venta_id, true), '') <> 'si'
                    or exists (select 1 from movimientos_stock
                               where venta_id = new.venta_id and tipo = 'venta' and articulo_id = new.articulo_id
                                 and ubicacion_stock_id = new.ubicacion_stock_id) then
                raise exception 'El stock de la venta % sale una sola vez, al registrarla.', new.venta_id
                    using errcode = 'check_violation';
            end if;
            if new.cantidad <> -vendida then
                raise exception 'El movimiento de la venta % saca la cantidad vendida.', new.venta_id
                    using errcode = 'check_violation';
            end if;
        else
            if new.cantidad < 0 then
                raise exception 'La anulación y la devolución de una venta suman stock.' using errcode = 'check_violation';
            end if;
            if (new.tipo = 'anulacion') <> (estado_v = 'anulada') then
                raise exception 'La anulación es de una venta anulada, y la devolución, de una confirmada.'
                    using errcode = 'check_violation';
            end if;
            select coalesce(sum(cantidad), 0) into vuelto from movimientos_stock
            where venta_id = new.venta_id and tipo in ('anulacion', 'devolucion') and articulo_id = new.articulo_id
              and ubicacion_stock_id = new.ubicacion_stock_id;
            if vuelto + new.cantidad > vendida then
                raise exception 'Lo que vuelve al stock de la venta % supera lo vendido.', new.venta_id
                    using errcode = 'check_violation';
            end if;
        end if;
    end if;
    return new;
end;
$$;

