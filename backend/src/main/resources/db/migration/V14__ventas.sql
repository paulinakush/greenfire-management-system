    usuario_id      bigint        not null references usuarios (id),
    fecha_hora      timestamptz   not null default now(),
    motivo          text          not null check (length(trim(motivo)) > 0),
    total           numeric(14,2) not null check (total >= 0),
    nota_credito_id bigint        not null references comprobantes (id),
    sesion_caja_id  bigint        references sesiones_caja (id),
    created_at      timestamptz   not null default now(),
    updated_at      timestamptz   not null default now()
);

create unique index uq_devoluciones_venta_nota_credito on devoluciones_venta (nota_credito_id);
create index ix_devoluciones_venta_venta on devoluciones_venta (venta_id);

