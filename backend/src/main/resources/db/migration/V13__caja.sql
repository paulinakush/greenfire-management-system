-- Etapa 3, módulo 4: caja de los locales. Ver docs/modelo-datos.dbml.
--
-- Garantías de la base, aunque se escriba por fuera de la aplicación:
-- - Solo los locales tienen caja, con una sola sesión abierta por local (índice único parcial).
-- - Los movimientos solo se insertan, en una sesión abierta. Un error se corrige con un movimiento contrario.
-- - El cierre pasa la sesión de abierta a cerrada una vez, con los totales que salen de sus movimientos.
-- - Después del cierre, solo la corrección autorizada cambia el efectivo contado y la diferencia, con motivo.

create table sesiones_caja (
    id                       bigint generated by default as identity primary key,
    ambito_id                bigint        not null references ambitos (id),
    usuario_apertura_id      bigint        not null references usuarios (id),
    usuario_cierre_id        bigint        references usuarios (id),
    abierta_at               timestamptz   not null default now(),
    cerrada_at               timestamptz,
    saldo_inicial            numeric(14,2) not null check (saldo_inicial >= 0),
    total_efectivo           numeric(14,2),
    total_transferencia      numeric(14,2),
    total_billetera          numeric(14,2),
    total_general            numeric(14,2),
    ingresos_efectivo        numeric(14,2) check (ingresos_efectivo >= 0),
    egresos_efectivo         numeric(14,2) check (egresos_efectivo >= 0),
    efectivo_esperado        numeric(14,2),
    efectivo_contado         numeric(14,2) check (efectivo_contado >= 0),
    diferencia               numeric(14,2),
    estado                   varchar(10)   not null default 'abierta' check (estado in ('abierta', 'cerrada')),
    observaciones            text,
    corregida_por_usuario_id bigint        references usuarios (id),
    corregida_at             timestamptz,
    motivo_correccion        text,
    created_at               timestamptz   not null default now(),
    updated_at               timestamptz   not null default now(),
    -- Con coalesce: un CHECK que da null no falla.
    constraint sesiones_caja_estado_coherente check (coalesce(
        (estado = 'abierta' and usuario_cierre_id is null and cerrada_at is null and total_efectivo is null
            and total_transferencia is null and total_billetera is null and total_general is null
            and ingresos_efectivo is null and egresos_efectivo is null and efectivo_esperado is null
            and efectivo_contado is null and diferencia is null and observaciones is null)
        or (estado = 'cerrada' and usuario_cierre_id is not null and cerrada_at is not null
            and total_efectivo is not null and total_transferencia is not null and total_billetera is not null
            and total_general is not null and ingresos_efectivo is not null and egresos_efectivo is not null
            and efectivo_esperado is not null and efectivo_contado is not null and diferencia is not null), false)),
    constraint sesiones_caja_cierre_cuadra check (estado = 'abierta' or (
        total_general = total_efectivo + total_transferencia + total_billetera
        and efectivo_esperado = saldo_inicial + total_efectivo + ingresos_efectivo - egresos_efectivo
        and diferencia = efectivo_contado - efectivo_esperado)),
    constraint sesiones_caja_correccion_coherente check (coalesce(
        (corregida_por_usuario_id is null and corregida_at is null and motivo_correccion is null)
        or (estado = 'cerrada' and corregida_por_usuario_id is not null and corregida_at is not null
            and length(trim(motivo_correccion)) > 0), false)),
    constraint sesiones_caja_fechas check (cerrada_at is null or cerrada_at >= abierta_at)
);

-- Una sola sesión abierta por local.
create unique index uq_sesiones_caja_abierta on sesiones_caja (ambito_id) where estado = 'abierta';
create index ix_sesiones_caja_ambito on sesiones_caja (ambito_id, abierta_at desc);

create table movimientos_caja (
    id                    bigint generated by default as identity primary key,
    sesion_caja_id        bigint        not null references sesiones_caja (id),
    usuario_id            bigint        not null references usuarios (id),
    origen                varchar(10)   not null check (origen in ('manual', 'venta', 'cobranza', 'devolucion')),
    tipo                  varchar(7)    not null check (tipo in ('ingreso', 'egreso')),
    rubro                 varchar(12)   check (rubro in ('gasto', 'retiro', 'aporte', 'pago_fabrica', 'otro')),
    medio_pago            varchar(20)   not null check (medio_pago in ('efectivo', 'transferencia', 'billetera_virtual')),
    monto                 numeric(14,2) not null check (monto > 0),
    fecha_hora            timestamptz   not null default now(),
    observacion           text,
    corrige_movimiento_id bigint        references movimientos_caja (id),
    created_at            timestamptz   not null default now(),
    updated_at            timestamptz   not null default now(),
    -- Los manuales llevan rubro y observación; los de ventas, cobranzas y devoluciones, no.
    constraint movimientos_caja_rubro_segun_origen check ((origen = 'manual') = (rubro is not null)),
    constraint movimientos_caja_observacion_manual
        check (origen <> 'manual' or coalesce(length(trim(observacion)), 0) > 0),
    constraint movimientos_caja_tipo_segun_origen check (
        origen = 'manual'
        or (origen in ('venta', 'cobranza') and tipo = 'ingreso')
        or (origen = 'devolucion' and tipo = 'egreso')),
    -- Gasto, retiro y pago a la fábrica son egresos y el aporte es un ingreso, salvo en la corrección de un error.
    constraint movimientos_caja_tipo_segun_rubro check (
        origen <> 'manual' or corrige_movimiento_id is not null or rubro = 'otro'
        or (rubro in ('gasto', 'retiro', 'pago_fabrica') and tipo = 'egreso')
        or (rubro = 'aporte' and tipo = 'ingreso')),
    constraint movimientos_caja_correccion_manual check (corrige_movimiento_id is null or origen = 'manual')
);

create index ix_movimientos_caja_sesion on movimientos_caja (sesion_caja_id, id);
create index ix_movimientos_caja_corrige on movimientos_caja (corrige_movimiento_id)
    where corrige_movimiento_id is not null;

-- ---------------------------------------------------------------------------
-- Totales de una sesión, a partir de sus movimientos
-- ---------------------------------------------------------------------------

-- Cobros netos por medio (ventas + cobranzas - devoluciones) y movimientos manuales en efectivo. La aplicación
-- calcula lo mismo en CierreCaja; el cierre se verifica contra esta función.
create function caja_totales(sesion bigint,
    out total_efectivo numeric, out total_transferencia numeric, out total_billetera numeric,
    out ingresos_efectivo numeric, out egresos_efectivo numeric)
language sql stable as $$
    select
        coalesce(sum(case when tipo = 'ingreso' then monto else -monto end)
                 filter (where origen <> 'manual' and medio_pago = 'efectivo'), 0),
        coalesce(sum(case when tipo = 'ingreso' then monto else -monto end)
                 filter (where origen <> 'manual' and medio_pago = 'transferencia'), 0),
        coalesce(sum(case when tipo = 'ingreso' then monto else -monto end)
                 filter (where origen <> 'manual' and medio_pago = 'billetera_virtual'), 0),
        coalesce(sum(monto) filter (where origen = 'manual' and medio_pago = 'efectivo' and tipo = 'ingreso'), 0),
        coalesce(sum(monto) filter (where origen = 'manual' and medio_pago = 'efectivo' and tipo = 'egreso'), 0)
    from movimientos_caja
    where sesion_caja_id = sesion;
$$;

-- ---------------------------------------------------------------------------
-- Sesiones: nacen abiertas, se cierran una vez y después solo se corrigen
-- ---------------------------------------------------------------------------

create function sesiones_caja_validar() returns trigger
language plpgsql as $$
declare
    t record;
begin
    if tg_op = 'DELETE' or tg_op = 'TRUNCATE' then
        raise exception 'Las sesiones de caja no se borran (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;

    if tg_op = 'INSERT' then
        if new.estado <> 'abierta' then
            raise exception 'Una sesión de caja nace abierta.' using errcode = 'check_violation';
        end if;
        if not exists (select 1 from ambitos where id = new.ambito_id and tipo = 'local') then
            raise exception 'Solo los locales tienen caja: la fábrica no.' using errcode = 'check_violation';
        end if;
        return new;
    end if;

    -- UPDATE: la apertura no cambia nunca
    if (new.ambito_id, new.usuario_apertura_id, new.abierta_at, new.saldo_inicial)
            is distinct from (old.ambito_id, old.usuario_apertura_id, old.abierta_at, old.saldo_inicial) then
        raise exception 'Los datos de la apertura de la caja % no se modifican.', old.id
            using errcode = 'insufficient_privilege';
    end if;

    if old.estado = 'abierta' then
        -- el cierre, con los totales de sus movimientos
        if new.estado <> 'cerrada' then
            raise exception 'La caja % está abierta: solo se puede cerrar.', old.id
                using errcode = 'insufficient_privilege';
        end if;
        if new.corregida_por_usuario_id is not null then
            raise exception 'Se corrige un cierre, no una caja abierta.' using errcode = 'check_violation';
        end if;
        select * into t from caja_totales(old.id);
        if (new.total_efectivo, new.total_transferencia, new.total_billetera, new.ingresos_efectivo,
                new.egresos_efectivo)
                is distinct from
                (t.total_efectivo, t.total_transferencia, t.total_billetera, t.ingresos_efectivo, t.egresos_efectivo) then
            raise exception 'Los totales del cierre de la caja % no son los de sus movimientos.', old.id
                using errcode = 'check_violation';
        end if;
        return new;
    end if;

    -- cerrada: solo la corrección autorizada, que registra quién, cuándo y por qué
    if new.corregida_at is null or new.corregida_at is not distinct from old.corregida_at then
        raise exception 'La caja % está cerrada: solo se corrige el efectivo contado, con motivo.', old.id
            using errcode = 'insufficient_privilege';
    end if;
    if (to_jsonb(new) - array['efectivo_contado', 'diferencia', 'corregida_por_usuario_id', 'corregida_at',
                              'motivo_correccion', 'updated_at'])
            <> (to_jsonb(old) - array['efectivo_contado', 'diferencia', 'corregida_por_usuario_id', 'corregida_at',
                                      'motivo_correccion', 'updated_at']) then
        raise exception 'En la corrección de la caja % solo cambian el efectivo contado y la diferencia.', old.id
            using errcode = 'insufficient_privilege';
    end if;
    return new;
end;
$$;

create trigger sesiones_caja_validar
    before insert or update or delete on sesiones_caja
    for each row execute function sesiones_caja_validar();

create trigger sesiones_caja_sin_truncate
    before truncate on sesiones_caja
    for each statement execute function sesiones_caja_validar();

-- ---------------------------------------------------------------------------
-- Movimientos: solo se insertan, en una sesión abierta
-- ---------------------------------------------------------------------------

-- Bloquea la sesión (FOR SHARE) mientras inserta: un cierre en curso espera al movimiento, y un movimiento que
-- llega durante un cierre espera a que termine y ve la caja cerrada.
create function movimientos_caja_validar() returns trigger
language plpgsql as $$
declare
    estado_sesion varchar;
    original      record;
    corregido     numeric;
begin
    if tg_op <> 'INSERT' then
        raise exception 'Los movimientos de caja no se modifican ni se borran: un error se corrige con un movimiento '
            'contrario (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;

    select estado into estado_sesion from sesiones_caja where id = new.sesion_caja_id for share;
    if estado_sesion <> 'abierta' then
        raise exception 'La caja % está cerrada: no admite movimientos.', new.sesion_caja_id
            using errcode = 'check_violation';
    end if;

    if new.corrige_movimiento_id is not null then
        select * into original from movimientos_caja where id = new.corrige_movimiento_id for update;
        if original.sesion_caja_id <> new.sesion_caja_id or original.origen <> 'manual'
                or original.corrige_movimiento_id is not null or original.rubro <> new.rubro
                or original.medio_pago <> new.medio_pago or original.tipo = new.tipo then
            raise exception 'La corrección del movimiento % es un movimiento manual contrario, de la misma caja, '
                'con su rubro y su medio.', original.id
                using errcode = 'check_violation';
        end if;
        select coalesce(sum(monto), 0) into corregido from movimientos_caja where corrige_movimiento_id = original.id;
        if corregido + new.monto > original.monto then
            raise exception 'Las correcciones del movimiento % superan su monto.', original.id
                using errcode = 'check_violation';
        end if;
    end if;
    return new;
end;
$$;

create trigger movimientos_caja_validar
    before insert or update or delete on movimientos_caja
    for each row execute function movimientos_caja_validar();

create trigger movimientos_caja_sin_truncate
    before truncate on movimientos_caja
    for each statement execute function movimientos_caja_validar();
