-- Etapa 1: entidades fiscales, ámbitos, puntos de venta, usuarios por ámbito,
-- auditoría y sesiones. Ver docs/modelo-datos.dbml.

-- ---------------------------------------------------------------------------
-- Entidades fiscales y ámbitos
-- ---------------------------------------------------------------------------

create table entidades_fiscales (
    id                     bigint generated by default as identity primary key,
    razon_social           varchar(200) not null,
    cuit                   varchar(11)  not null unique check (cuit ~ '^[0-9]{11}$'),
    condicion_iva          varchar(30)  not null check (condicion_iva in
                               ('responsable_inscripto', 'monotributo', 'exento', 'consumidor_final')),
    domicilio_fiscal       varchar(255),
    arca_certificado_ref   varchar(255),
    arca_certificado_vence date,
    activo                 boolean      not null default true,
    created_at             timestamptz  not null default now(),
    updated_at             timestamptz  not null default now()
);

create table ambitos (
    id                bigint generated by default as identity primary key,
    tipo              varchar(10)  not null check (tipo in ('fabrica', 'local')),
    nombre            varchar(120) not null,
    entidad_fiscal_id bigint       not null references entidades_fiscales (id),
    direccion         varchar(255),
    telefono          varchar(50),
    email             varchar(255),
    horarios          varchar(255),
    visible_web       boolean      not null default false,
    activo            boolean      not null default true,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    -- permite que puntos_venta exija que el ámbito sea de la misma entidad fiscal
    unique (id, entidad_fiscal_id)
);

-- Hay una sola fábrica.
create unique index uq_ambitos_una_fabrica on ambitos (tipo) where tipo = 'fabrica';

create table puntos_venta (
    id                bigint generated by default as identity primary key,
    entidad_fiscal_id bigint       not null references entidades_fiscales (id),
    ambito_id         bigint       not null,
    numero            integer      not null check (numero between 1 and 99999),
    descripcion       varchar(120),
    activo            boolean      not null default true,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    unique (entidad_fiscal_id, numero),
    foreign key (ambito_id, entidad_fiscal_id) references ambitos (id, entidad_fiscal_id)
);

create table punto_venta_comprobantes (
    id             bigint generated by default as identity primary key,
    punto_venta_id bigint      not null references puntos_venta (id) on delete cascade,
    tipo           varchar(20) not null check (tipo in
                       ('factura', 'nota_credito', 'remito', 'recibo', 'presupuesto')),
    letra          varchar(1)  not null check (letra in ('A', 'B', 'C', 'X')),
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    unique (punto_venta_id, tipo, letra)
);

-- ---------------------------------------------------------------------------
-- Usuarios y perfiles por ámbito
-- ---------------------------------------------------------------------------

create table usuarios (
    id                bigint generated by default as identity primary key,
    nombre            varchar(120) not null,
    email             varchar(255) not null,
    password_hash     varchar(100) not null,
    es_admin_tecnico  boolean      not null default false,
    activo            boolean      not null default true,
    intentos_fallidos integer      not null default 0,
    bloqueado_hasta   timestamptz,
    reset_token_hash  varchar(100),
    reset_token_vence timestamptz,
    ultimo_acceso     timestamptz,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now()
);

create unique index uq_usuarios_email on usuarios (lower(email));

create table usuario_ambitos (
    id                    bigint generated by default as identity primary key,
    usuario_id            bigint      not null references usuarios (id),
    ambito_id             bigint      not null references ambitos (id),
    perfil                varchar(20) not null check (perfil in
                              ('dueno_fabrica', 'dueno_local', 'empleado_local')),
    activo                boolean     not null default true,
    creado_por_usuario_id bigint      references usuarios (id),
    created_at            timestamptz not null default now(),
    updated_at            timestamptz not null default now(),
    unique (usuario_id, ambito_id)
);

create index ix_usuario_ambitos_ambito on usuario_ambitos (ambito_id);

-- ---------------------------------------------------------------------------
-- Auditoría
-- ---------------------------------------------------------------------------

create table auditorias (
    id              bigint generated by default as identity primary key,
    usuario_id      bigint       references usuarios (id),
    perfil          varchar(20)  check (perfil in ('dueno_fabrica', 'dueno_local', 'empleado_local')),
    ambito_id       bigint       references ambitos (id),
    accion          varchar(60)  not null,
    entidad         varchar(60),
    entidad_id      bigint,
    detalle         text,
    email_intentado varchar(255),
    ip              varchar(45),
    fecha_hora      timestamptz  not null default now(),
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now()
);

create index ix_auditorias_ambito_fecha on auditorias (ambito_id, fecha_hora desc);
create index ix_auditorias_usuario on auditorias (usuario_id);

-- ---------------------------------------------------------------------------
-- Sesiones HTTP (esquema estándar de Spring Session JDBC para PostgreSQL)
-- ---------------------------------------------------------------------------

create table spring_session (
    primary_id            char(36)     not null,
    session_id            char(36)     not null,
    creation_time         bigint       not null,
    last_access_time      bigint       not null,
    max_inactive_interval int          not null,
    expiry_time           bigint       not null,
    principal_name        varchar(100),
    constraint spring_session_pk primary key (primary_id)
);

create unique index spring_session_ix1 on spring_session (session_id);
create index spring_session_ix2 on spring_session (expiry_time);
create index spring_session_ix3 on spring_session (principal_name);

create table spring_session_attributes (
    session_primary_id char(36)     not null,
    attribute_name     varchar(200) not null,
    attribute_bytes    bytea        not null,
    constraint spring_session_attributes_pk primary key (session_primary_id, attribute_name),
    constraint spring_session_attributes_fk foreign key (session_primary_id)
        references spring_session (primary_id) on delete cascade
);
