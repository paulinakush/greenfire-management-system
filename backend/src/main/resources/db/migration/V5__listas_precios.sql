-- Etapa 2, módulo 2: listas de precios, precios por artículo e historial. Ver docs/modelo-datos.dbml.

create table listas_precios (
    id                bigint generated by default as identity primary key,
    ambito_id         bigint       not null references ambitos (id),
    nombre            varchar(120) not null,
    precios_con_iva   boolean      not null,
    es_predeterminada boolean      not null default false,
    activo            boolean      not null default true,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    -- la predeterminada es la de venta al público: no se puede desactivar
    check (activo or not es_predeterminada)
);

create unique index uq_listas_precios_nombre on listas_precios (ambito_id, lower(nombre));
create unique index uq_listas_precios_predeterminada on listas_precios (ambito_id) where es_predeterminada;

-- Si la entidad del ámbito no discrimina IVA (todo lo que no es responsable inscripto), el precio de la lista
-- es el precio final: la lista va siempre con IVA.
-- Se valida solo al crear la lista o al cambiar su ámbito o si es con IVA. Si después cambia la condición de la
-- entidad, las listas quedan como estaban (la edición de la entidad lo advierte) y se pueden seguir editando.
create function listas_precios_iva_segun_entidad() returns trigger
language plpgsql as $$
declare
    condicion varchar;
begin
    if tg_op = 'UPDATE' and new.ambito_id = old.ambito_id and new.precios_con_iva = old.precios_con_iva then
        return new;
    end if;
    select e.condicion_iva into condicion
    from ambitos a join entidades_fiscales e on e.id = a.entidad_fiscal_id
    where a.id = new.ambito_id;
    if condicion <> 'responsable_inscripto' and not new.precios_con_iva then
        raise exception 'La entidad del ámbito % no discrimina IVA: la lista debe tener precios con IVA.', new.ambito_id
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger listas_precios_iva_segun_entidad
    before insert or update of ambito_id, precios_con_iva on listas_precios
    for each row execute function listas_precios_iva_segun_entidad();

create table lista_precios_items (
    id          bigint generated by default as identity primary key,
    lista_id    bigint        not null references listas_precios (id),
    articulo_id bigint        not null references articulos (id),
    precio      numeric(14,2) not null check (precio > 0),
    created_at  timestamptz   not null default now(),
    updated_at  timestamptz   not null default now(),
    unique (lista_id, articulo_id)
);

create index ix_lista_precios_items_articulo on lista_precios_items (articulo_id);

-- Una lista tiene precios de lo que su ámbito vende: los productos terminados de la fábrica y la reventa del
-- propio ámbito. Los insumos no se venden, y la reventa de un local no entra en las listas de otro.
create function lista_precios_items_articulo_valido() returns trigger
language plpgsql as $$
declare
    ambito_lista    bigint;
    ambito_articulo bigint;
    tipo_articulo   varchar;
begin
    select ambito_id into ambito_lista from listas_precios where id = new.lista_id;
    select ambito_id, tipo into ambito_articulo, tipo_articulo from articulos where id = new.articulo_id;
    if not (tipo_articulo = 'producto_terminado'
            or (tipo_articulo = 'reventa' and ambito_articulo = ambito_lista)) then
        raise exception 'La lista % no puede tener precio del artículo %.', new.lista_id, new.articulo_id
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger lista_precios_items_articulo_valido
    before insert or update of lista_id, articulo_id on lista_precios_items
    for each row execute function lista_precios_items_articulo_valido();

create table historial_precios (
    id              bigint generated by default as identity primary key,
    lista_id        bigint        not null references listas_precios (id),
    articulo_id     bigint        not null references articulos (id),
    precio_anterior numeric(14,2),
    precio_nuevo    numeric(14,2),
    usuario_id      bigint        not null references usuarios (id),
    fecha_hora      timestamptz   not null default now(),
    created_at      timestamptz   not null default now(),
    updated_at      timestamptz   not null default now(),
    check (precio_anterior is not null or precio_nuevo is not null)
);

create index ix_historial_precios_lista on historial_precios (lista_id, articulo_id, fecha_hora desc);

-- El historial no se modifica ni se borra, igual que la auditoría (V2).
create function historial_precios_inmutable() returns trigger
language plpgsql as $$
begin
    raise exception 'El historial de precios no se puede modificar ni borrar (operación % rechazada).', tg_op
        using errcode = 'insufficient_privilege';
end;
$$;

create trigger historial_precios_sin_update_ni_delete
    before update or delete on historial_precios
    for each row execute function historial_precios_inmutable();

create trigger historial_precios_sin_truncate
    before truncate on historial_precios
    for each statement execute function historial_precios_inmutable();
