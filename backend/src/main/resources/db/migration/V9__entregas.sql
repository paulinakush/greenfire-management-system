-- Etapa 2, módulo 6: entregas de la fábrica a los locales. Ver docs/modelo-datos.dbml.
-- Se construyen en esta etapa pero no se usan en producción hasta la etapa 3 (cuenta corriente).

create table entregas (
    id                     bigint generated by default as identity primary key,
    ambito_origen_id       bigint        not null references ambitos (id),
    ambito_destino_id      bigint        not null references ambitos (id),
    ubicacion_origen_id    bigint        not null references ubicaciones_stock (id),
    ubicacion_destino_id   bigint        references ubicaciones_stock (id),
    lista_precios_id       bigint        not null references listas_precios (id),
    estado                 varchar(25)   not null default 'enviada'
                               check (estado in ('enviada', 'recibida', 'diferencia_informada', 'anulada')),
    usuario_envio_id       bigint        not null references usuarios (id),
    fecha_envio            timestamptz   not null default now(),
    usuario_recepcion_id   bigint        references usuarios (id),
    fecha_recepcion        timestamptz,
    usuario_anulacion_id   bigint        references usuarios (id),
    anulada_at             timestamptz,
    resolucion_diferencia  varchar(10)   check (resolucion_diferencia in ('reingreso', 'perdida')),
    motivo_resolucion      varchar(255),
    usuario_resolucion_id  bigint        references usuarios (id),
    diferencia_resuelta_at timestamptz,
    total                  numeric(14,2) not null check (total >= 0),
    observaciones          text,
    observaciones_recepcion text,
    created_at             timestamptz   not null default now(),
    updated_at             timestamptz   not null default now(),
    check (ambito_origen_id <> ambito_destino_id),
    -- cada estado con sus datos: la recepción y la anulación se excluyen
    constraint entregas_estado_coherente check (
        (estado = 'enviada'
            and ubicacion_destino_id is null and usuario_recepcion_id is null and fecha_recepcion is null
            and usuario_anulacion_id is null and anulada_at is null)
        or (estado in ('recibida', 'diferencia_informada')
            and ubicacion_destino_id is not null and usuario_recepcion_id is not null and fecha_recepcion is not null
            and usuario_anulacion_id is null and anulada_at is null)
        or (estado = 'anulada'
            and ubicacion_destino_id is null and usuario_recepcion_id is null and fecha_recepcion is null
            and usuario_anulacion_id is not null and anulada_at is not null)),
    -- solo se resuelve una diferencia informada, con forma, motivo, usuario y fecha
    constraint entregas_resolucion_coherente check (
        (resolucion_diferencia is null and motivo_resolucion is null and usuario_resolucion_id is null
            and diferencia_resuelta_at is null)
        or (estado = 'diferencia_informada' and resolucion_diferencia is not null
            and coalesce(length(trim(motivo_resolucion)), 0) > 0 and usuario_resolucion_id is not null
            and diferencia_resuelta_at is not null))
);

create index ix_entregas_origen on entregas (ambito_origen_id, id desc);
create index ix_entregas_destino on entregas (ambito_destino_id, id desc);

-- Al crearla: sale de la fábrica hacia un local, desde una ubicación y con una lista de la fábrica.
-- Después, solo estas transiciones:
--   enviada -> recibida o diferencia_informada (con la ubicación de destino, del local) o anulada;
--   diferencia_informada sin resolver -> resuelta, una sola vez.
-- Nada más cambia, y ninguna entrega se borra.
create function entregas_validar() returns trigger
language plpgsql as $$
begin
    if tg_op = 'DELETE' or tg_op = 'TRUNCATE' then
        raise exception 'Las entregas no se borran: se anulan (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;

    if tg_op = 'INSERT' then
        if new.estado <> 'enviada' or new.ubicacion_destino_id is not null or new.diferencia_resuelta_at is not null then
            raise exception 'Una entrega nace enviada.' using errcode = 'check_violation';
        end if;
        if not exists (select 1 from ambitos where id = new.ambito_origen_id and tipo = 'fabrica') then
            raise exception 'Una entrega sale de la fábrica.' using errcode = 'check_violation';
        end if;
        if not exists (select 1 from ambitos where id = new.ambito_destino_id and tipo = 'local') then
            raise exception 'Una entrega va a un local.' using errcode = 'check_violation';
        end if;
        if not exists (select 1 from ubicaciones_stock
                       where id = new.ubicacion_origen_id and ambito_id = new.ambito_origen_id) then
            raise exception 'La ubicación de origen debe ser de la fábrica.' using errcode = 'check_violation';
        end if;
        if not exists (select 1 from listas_precios
                       where id = new.lista_precios_id and ambito_id = new.ambito_origen_id) then
            raise exception 'La lista de precios debe ser de la fábrica.' using errcode = 'check_violation';
        end if;
        return new;
    end if;

    -- UPDATE: lo que se fijó al enviar no cambia nunca
    if (new.ambito_origen_id, new.ambito_destino_id, new.ubicacion_origen_id, new.lista_precios_id,
        new.usuario_envio_id, new.fecha_envio, new.total, new.observaciones)
       is distinct from
       (old.ambito_origen_id, old.ambito_destino_id, old.ubicacion_origen_id, old.lista_precios_id,
        old.usuario_envio_id, old.fecha_envio, old.total, old.observaciones) then
        raise exception 'Los datos del envío de la entrega % no se modifican.', old.id
            using errcode = 'insufficient_privilege';
    end if;

    if old.estado = 'enviada' then
        if new.estado = 'enviada' then
            raise exception 'La entrega % sigue enviada: no hay nada que modificar.', old.id
                using errcode = 'insufficient_privilege';
        end if;
        if new.estado in ('recibida', 'diferencia_informada')
                and not exists (select 1 from ubicaciones_stock
                                where id = new.ubicacion_destino_id and ambito_id = new.ambito_destino_id) then
            raise exception 'La ubicación de destino debe ser del local.' using errcode = 'check_violation';
        end if;
        -- la recepción o la anulación; la resolución recién después de informar la diferencia
        if new.diferencia_resuelta_at is not null then
            raise exception 'La diferencia se resuelve después de la recepción.' using errcode = 'check_violation';
        end if;
        return new;
    end if;

    if old.estado = 'diferencia_informada' and old.diferencia_resuelta_at is null
            and new.estado = 'diferencia_informada' and new.diferencia_resuelta_at is not null
            and (new.ubicacion_destino_id, new.usuario_recepcion_id, new.fecha_recepcion, new.observaciones_recepcion)
                is not distinct from
                (old.ubicacion_destino_id, old.usuario_recepcion_id, old.fecha_recepcion, old.observaciones_recepcion) then
        return new;
    end if;

    if old.estado = 'diferencia_informada' and old.diferencia_resuelta_at is not null then
        raise exception 'La diferencia de la entrega % ya está resuelta: no se modifica.', old.id
            using errcode = 'insufficient_privilege';
    end if;
    raise exception 'La entrega % está %: no se puede modificar.', old.id, old.estado
        using errcode = 'insufficient_privilege';
end;
$$;

create trigger entregas_validar
    before insert or update or delete on entregas
    for each row execute function entregas_validar();

create trigger entregas_sin_truncate
    before truncate on entregas
    for each statement execute function entregas_validar();

create table detalle_entregas (
    id                bigint generated by default as identity primary key,
    entrega_id        bigint        not null references entregas (id),
    articulo_id       bigint        not null references articulos (id),
    lote_id           bigint,
    cantidad_enviada  numeric(14,3) not null check (cantidad_enviada > 0),
    cantidad_recibida numeric(14,3) check (cantidad_recibida >= 0),
    precio_unitario   numeric(14,2) not null check (precio_unitario >= 0),
    subtotal          numeric(14,2) not null,
    created_at        timestamptz   not null default now(),
    updated_at        timestamptz   not null default now(),
    constraint detalle_entregas_recibida_no_mayor check (cantidad_recibida <= cantidad_enviada),
    constraint detalle_entregas_subtotal check (subtotal = round(cantidad_enviada * precio_unitario, 2))
);

-- Un renglón por artículo y lote (el lote es null hasta la etapa 4).
create unique index uq_detalle_entregas_renglon on detalle_entregas (entrega_id, articulo_id, coalesce(lote_id, 0));

-- Los renglones se cargan con la entrega enviada y solo son productos terminados de la fábrica, en cantidades
-- enteras si se miden en unidades. Después solo se carga la cantidad recibida, una vez y con la entrega todavía
-- enviada (la recepción carga el detalle antes de cambiar el estado). Nada se borra.
create function detalle_entregas_validar() returns trigger
language plpgsql as $$
declare
    estado_e varchar;
    origen   bigint;
    unidad   varchar;
begin
    if tg_op = 'DELETE' or tg_op = 'TRUNCATE' then
        raise exception 'El detalle de una entrega no se borra (operación % rechazada).', tg_op
            using errcode = 'insufficient_privilege';
    end if;
    select estado, ambito_origen_id into estado_e, origen from entregas where id = new.entrega_id;
    if estado_e <> 'enviada' then
        raise exception 'La entrega % está %: su detalle no se puede modificar.', new.entrega_id, estado_e
            using errcode = 'insufficient_privilege';
    end if;

    if tg_op = 'INSERT' then
        if new.cantidad_recibida is not null then
            raise exception 'La cantidad recibida se carga al recibir.' using errcode = 'check_violation';
        end if;
        select unidad_medida into unidad from articulos
        where id = new.articulo_id and ambito_id = origen and tipo = 'producto_terminado';
        if not found then
            raise exception 'Una entrega solo lleva productos terminados de la fábrica.' using errcode = 'check_violation';
        end if;
        if unidad = 'unidad' and new.cantidad_enviada <> trunc(new.cantidad_enviada) then
            raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
                using errcode = 'check_violation';
        end if;
        return new;
    end if;

    if (new.entrega_id, new.articulo_id, new.lote_id, new.cantidad_enviada, new.precio_unitario, new.subtotal)
           is distinct from
       (old.entrega_id, old.articulo_id, old.lote_id, old.cantidad_enviada, old.precio_unitario, old.subtotal)
       or old.cantidad_recibida is not null then
        raise exception 'Del detalle de la entrega % solo se carga la cantidad recibida, una vez.', old.entrega_id
            using errcode = 'insufficient_privilege';
    end if;
    select unidad_medida into unidad from articulos where id = new.articulo_id;
    if unidad = 'unidad' and new.cantidad_recibida <> trunc(new.cantidad_recibida) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    return new;
end;
$$;

create trigger detalle_entregas_validar
    before insert or update or delete on detalle_entregas
    for each row execute function detalle_entregas_validar();

create trigger detalle_entregas_sin_truncate
    before truncate on detalle_entregas
    for each statement execute function detalle_entregas_validar();

-- Al confirmar la transacción, cada entrega tiene al menos un renglón y su total es la suma de los subtotales.
create function entregas_verificar_total() returns trigger
language plpgsql as $$
declare
    id_entrega bigint;
    renglones  integer;
    suma       numeric;
    total_e    numeric;
begin
    -- se dispara desde las dos tablas: en entregas el id es el de la fila, en detalle_entregas el de su entrega
    id_entrega := case when tg_table_name = 'entregas' then (to_jsonb(new) ->> 'id')::bigint
                       else (to_jsonb(new) ->> 'entrega_id')::bigint end;
    select count(*), coalesce(sum(subtotal), 0) into renglones, suma from detalle_entregas where entrega_id = id_entrega;
    select total into total_e from entregas where id = id_entrega;
    if renglones = 0 then
        raise exception 'La entrega % no tiene renglones.', id_entrega using errcode = 'check_violation';
    end if;
    if suma <> total_e then
        raise exception 'El total de la entrega % (%) no es la suma de sus renglones (%).', id_entrega, total_e, suma
            using errcode = 'check_violation';
    end if;
    return null;
end;
$$;

create constraint trigger entregas_total
    after insert on entregas deferrable initially deferred
    for each row execute function entregas_verificar_total();

create constraint trigger detalle_entregas_total
    after insert on detalle_entregas deferrable initially deferred
    for each row execute function entregas_verificar_total();

-- Los movimientos de una entrega apuntan a ella.
alter table movimientos_stock add column entrega_id bigint references entregas (id);
alter table movimientos_stock add constraint movimientos_stock_entrega_segun_tipo
    check ((tipo in ('entrega_salida', 'entrega_recepcion', 'anulacion', 'devolucion')) = (entrega_id is not null));
create index ix_movimientos_stock_entrega on movimientos_stock (entrega_id) where entrega_id is not null;

-- Igual que en V7, más las reglas de los movimientos de una entrega: la salida, la anulación y la devolución son
-- de la ubicación de origen y la recepción de la de destino; la salida resta y los demás suman; y el artículo es
-- uno de los renglones de la entrega.
create or replace function movimientos_stock_validar() returns trigger
language plpgsql as $$
declare
    unidad    varchar;
    origen    bigint;
    destino   bigint;
    ubicacion bigint;
begin
    perform stock_articulo_valido_en_ubicacion(new.articulo_id, new.ubicacion_stock_id);
    select unidad_medida into unidad from articulos where id = new.articulo_id;
    if unidad = 'unidad' and new.cantidad <> trunc(new.cantidad) then
        raise exception 'La cantidad de un artículo que se mide en unidades debe ser entera.'
            using errcode = 'check_violation';
    end if;
    if new.conteo_id is not null
            and not exists (select 1 from conteos_stock
                            where id = new.conteo_id and ubicacion_stock_id = new.ubicacion_stock_id) then
        raise exception 'El movimiento del conteo % debe ser de la ubicación del conteo.', new.conteo_id
            using errcode = 'check_violation';
    end if;
    if new.entrega_id is not null then
        select ubicacion_origen_id, ubicacion_destino_id into origen, destino from entregas where id = new.entrega_id;
        ubicacion := case when new.tipo = 'entrega_recepcion' then destino else origen end;
        if ubicacion is distinct from new.ubicacion_stock_id then
            raise exception 'El movimiento de la entrega % no es de la ubicación que corresponde.', new.entrega_id
                using errcode = 'check_violation';
        end if;
        if (new.tipo = 'entrega_salida') <> (new.cantidad < 0) then
            raise exception 'En una entrega, la salida resta y la recepción, la anulación y la devolución suman.'
                using errcode = 'check_violation';
        end if;
        if not exists (select 1 from detalle_entregas
                       where entrega_id = new.entrega_id and articulo_id = new.articulo_id) then
            raise exception 'El artículo no es de la entrega %.', new.entrega_id using errcode = 'check_violation';
        end if;
    end if;
    return new;
end;
$$;
